/**
 * Real-pipeline compilation benchmark: chunked vs unchunked timing against the canned
 * `benchmarks/data/{small,medium,large,xlarge}.txt` datasets.
 *
 * Unlike the Rust and .NET wrappers (see #424), this module has no unchunked-vs-chunked
 * compiler-divergence risk: {@linkcode runCompiler} always drives both paths through the
 * same underlying {@linkcode compileFilters}/`compile()` pipeline, so a benchmark run here
 * measures chunking overhead alone.
 *
 * @module orchestration/benchmark
 */

import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import process from 'node:process';
import type { IConfiguration, ISource } from '../index.ts';
import { SourceType, TransformationType } from '../types/index.ts';
import { runCompiler } from './compiler.ts';
import { toJson } from './config-reader.ts';
import type { Logger } from './types.ts';
import { logger as defaultLogger } from './logger.ts';

/**
 * Canned benchmark dataset sizes, matching `benchmarks/data/{name}.txt` at the repo root
 * (generated by `benchmarks/generate_synthetic_data.py`).
 */
export const BENCHMARK_SIZES = ['small', 'medium', 'large', 'xlarge'] as const;

/** One of the canned {@linkcode BENCHMARK_SIZES} dataset names. */
export type BenchmarkSize = typeof BENCHMARK_SIZES[number];

/**
 * Transformations applied to every benchmark run, matching the canned
 * `benchmarks/data/config-*.json` fixtures' own transformation list.
 */
const BENCHMARK_TRANSFORMATIONS: TransformationType[] = [
  TransformationType.Deduplicate,
  TransformationType.RemoveEmptyLines,
  TransformationType.TrimLines,
];

/** Options controlling a {@linkcode runBenchmark} run. */
export interface BenchmarkOptions {
  /** Dataset size to benchmark: one of {@linkcode BENCHMARK_SIZES}, or `'all'`. */
  size: string;
  /** Directory containing the canned benchmark data; auto-discovered if omitted. */
  dataDir?: string;
  /** Number of identical duplicated sources for the chunked run (one per chunk). */
  sources: number;
  /** Max parallel workers for the chunked run. */
  maxParallel: number;
  /** Logger for progress output during the run. */
  logger?: Logger;
}

/** Result of benchmarking one canned dataset size, unchunked vs chunked. */
export interface BenchmarkRunResult {
  /** The dataset size this result is for. */
  size: string;
  /** Number of identical duplicated sources used for the chunked run. */
  sources: number;
  /** Max parallel workers used for the chunked run. */
  maxParallel: number;
  /** Whether the unchunked run succeeded. */
  unchunkedSuccess: boolean;
  /** Elapsed time of the unchunked run, in milliseconds. */
  unchunkedMs: number;
  /** Rule count produced by the unchunked run. */
  unchunkedRuleCount: number;
  /** Whether the chunked run succeeded. */
  chunkedSuccess: boolean;
  /** Elapsed time of the chunked run, in milliseconds. */
  chunkedMs: number;
  /** Rule count produced by the chunked run. */
  chunkedRuleCount: number;
  /**
   * `unchunkedMs / chunkedMs` - how much faster the chunked run was. `null` if either run
   * failed or the chunked run took 0ms (nothing to divide by).
   */
  speedup: number | null;
  /** Error message, if either run failed. */
  error?: string;
}

/**
 * Locates the repo's `benchmarks/data` directory by walking up from the current directory,
 * mirroring {@linkcode findDefaultConfig}'s search strategy.
 *
 * @param basePath - Directory to start searching from; defaults to the current working
 *   directory (Deno-native when available, otherwise `node:process`).
 * @returns Absolute path to `benchmarks/data`, or `undefined` if none was found.
 */
export function findBenchmarkDataDir(
  basePath: string = typeof Deno !== 'undefined' ? Deno.cwd() : process.cwd(),
): string | undefined {
  let dir = resolve(basePath);

  for (;;) {
    const candidate = join(dir, 'benchmarks', 'data');
    if (existsSync(candidate)) {
      return candidate;
    }

    const parent = dirname(dir);
    if (parent === dir) {
      return undefined;
    }
    dir = parent;
  }
}

/**
 * Builds an in-memory configuration with `numSources` identical sources, all pointing at
 * `dataPath` - the same "N copies of one file" shape as the (otherwise unusable,
 * machine-specific-path) canned `benchmarks/data/config-multi-Nsources.json` fixtures.
 * Identical sources keep the unchunked and chunked runs directly comparable: same total
 * workload, same total rule count after dedup, only the chunking strategy differs.
 *
 * @param size - Dataset size label, used only for the generated config's `name`.
 * @param dataPath - Path to the canned dataset file every source points at.
 * @param numSources - Number of identical sources to generate.
 * @returns A configuration ready to pass to {@linkcode runCompiler} (via a temp file).
 */
function buildBenchmarkConfig(size: string, dataPath: string, numSources: number): IConfiguration {
  const sources: ISource[] = [];
  for (let i = 0; i < Math.max(1, numSources); i++) {
    sources.push({
      name: `source-${i + 1}`,
      source: dataPath,
      type: SourceType.Adblock,
    });
  }

  return {
    name: `Benchmark - ${size}`,
    description: `Real-pipeline benchmark of the '${size}' canned dataset`,
    version: '1.0.0',
    sources,
    transformations: [...BENCHMARK_TRANSFORMATIONS],
  };
}

/** Outcome of a single {@linkcode runCompiler} invocation, normalized for benchmark reporting. */
interface RunOnceResult {
  /** Whether the compilation succeeded. */
  success: boolean;
  /** Elapsed compilation time, in milliseconds. */
  elapsedMs: number;
  /** Rule count in the compiled output. */
  ruleCount: number;
  /** Error message, if compilation failed. */
  error?: string;
}

/**
 * Runs one real compile of `config` via {@linkcode runCompiler}, unchunked or chunked
 * depending on `chunking`.
 */
async function runOnce(
  config: IConfiguration,
  chunking: boolean,
  maxParallel: number,
  logger: Logger,
): Promise<RunOnceResult> {
  const tempDir = mkdtempSync(join(tmpdir(), 'bloqr-benchmark-'));
  const tempConfigPath = join(tempDir, 'config.json');
  const tempOutputPath = join(tempDir, 'output.txt');

  try {
    writeFileSync(tempConfigPath, toJson(config));

    const result = await runCompiler({
      configPath: tempConfigPath,
      outputPath: tempOutputPath,
      validateConfig: false,
      enableChunking: chunking,
      maxParallel: chunking ? maxParallel : undefined,
      logger,
    });

    return {
      success: result.success,
      elapsedMs: result.elapsedMs,
      ruleCount: result.ruleCount,
      error: result.success ? undefined : result.errorMessage,
    };
  } catch (error) {
    return {
      success: false,
      elapsedMs: 0,
      ruleCount: 0,
      error: error instanceof Error ? error.message : String(error),
    };
  } finally {
    rmSync(tempDir, { recursive: true, force: true });
  }
}

/**
 * Benchmarks real compilation performance (chunked vs unchunked) across the requested
 * canned dataset size(s), using the same {@linkcode runCompiler} pipeline the `compile`
 * mode uses - not a simulation.
 *
 * @param options - Benchmark configuration.
 * @returns One result per benchmarked size, in the order requested.
 * @throws Error if `options.size` isn't a recognized size or `'all'`, or if no
 *   `benchmarks/data` directory could be found/resolved.
 */
export async function runBenchmark(options: BenchmarkOptions): Promise<BenchmarkRunResult[]> {
  const logger = options.logger ?? defaultLogger;

  const sizes: string[] = options.size.toLowerCase() === 'all'
    ? [...BENCHMARK_SIZES]
    : [options.size];

  for (const size of sizes) {
    if (!(BENCHMARK_SIZES as readonly string[]).includes(size)) {
      throw new Error(
        `Unknown benchmark size '${size}'. Expected one of: ${
          BENCHMARK_SIZES.join(', ')
        }, or 'all'.`,
      );
    }
  }

  const dataDir = options.dataDir ?? findBenchmarkDataDir();
  if (!dataDir) {
    throw new Error(
      'Could not find a benchmarks/data directory. Pass --benchmark-data-dir to point at ' +
        'one explicitly, or run this from within a clone of BloqrAI/bloqr-core.',
    );
  }

  const numSources = Math.max(1, options.sources);
  const results: BenchmarkRunResult[] = [];

  for (const size of sizes) {
    const dataPath = join(dataDir, `${size}.txt`);
    if (!existsSync(dataPath)) {
      results.push({
        size,
        sources: numSources,
        maxParallel: options.maxParallel,
        unchunkedSuccess: false,
        unchunkedMs: 0,
        unchunkedRuleCount: 0,
        chunkedSuccess: false,
        chunkedMs: 0,
        chunkedRuleCount: 0,
        speedup: null,
        error: `dataset file not found: ${dataPath}`,
      });
      continue;
    }

    logger.info(`Benchmarking '${size}' (${numSources} sources)...`);

    const config = buildBenchmarkConfig(size, dataPath, numSources);
    const unchunked = await runOnce(config, false, options.maxParallel, logger);
    const chunked = await runOnce(config, true, options.maxParallel, logger);

    const speedup = unchunked.success && chunked.success && chunked.elapsedMs > 0
      ? unchunked.elapsedMs / chunked.elapsedMs
      : null;

    results.push({
      size,
      sources: numSources,
      maxParallel: options.maxParallel,
      unchunkedSuccess: unchunked.success,
      unchunkedMs: unchunked.elapsedMs,
      unchunkedRuleCount: unchunked.ruleCount,
      chunkedSuccess: chunked.success,
      chunkedMs: chunked.elapsedMs,
      chunkedRuleCount: chunked.ruleCount,
      speedup,
      error: unchunked.error ?? chunked.error,
    });
  }

  return results;
}
