"""
Real-pipeline chunking benchmark, mirroring the Rust/.NET/TypeScript `benchmark`
subcommands (#415/#419).

Compiles the canned `benchmarks/data/{small,medium,large,xlarge}.txt` datasets through the
real `compile_rules()`/`compile_chunks_async()` pipeline - not a simulation - once unchunked
(all sources in a single compiler invocation, the same path the standard compile mode uses)
and once chunked (the same sources split one-per-chunk and compiled in parallel), so the two
runs cover identical total workloads and the chunking strategy is the intended variable.

Both `compile_rules()` and `compile_chunks_async()` resolve their compiler command through
the same `compiler._get_compiler_command()` (Deno + the JSR `@bloqr/compiler-core` package),
so a benchmark's speedup number measures chunking overhead alone - see #424, fixed for this
wrapper.
"""

from __future__ import annotations

import asyncio
import contextlib
import os
import tempfile
import uuid
from dataclasses import dataclass
from pathlib import Path

from bloqr_compiler.chunking import (
    ChunkingOptions,
    ChunkingStrategy,
    compile_chunks_async,
    split_into_chunks,
)
from bloqr_compiler.compiler import BloqrCompiler
from bloqr_compiler.config import CompilerConfiguration, FilterSource, to_json

#: Canned benchmark dataset sizes, matching `benchmarks/data/{name}.txt` at the repo root
#: (generated by `benchmarks/generate_synthetic_data.py`).
BENCHMARK_SIZES: tuple[str, ...] = ("small", "medium", "large", "xlarge")

#: Transformations applied to every benchmark run, matching the canned
#: `benchmarks/data/config-*.json` fixtures' own transformation list.
BENCHMARK_TRANSFORMATIONS: tuple[str, ...] = ("Deduplicate", "RemoveEmptyLines", "TrimLines")


@dataclass
class BenchmarkRunResult:
    """Result of benchmarking one canned dataset size, unchunked vs chunked."""

    size: str
    sources: int
    max_parallel: int
    unchunked_success: bool = False
    unchunked_ms: int = 0
    unchunked_rule_count: int = 0
    chunked_success: bool = False
    chunked_ms: int = 0
    chunked_rule_count: int = 0
    #: `unchunked_ms / chunked_ms` - how much faster the chunked run was, `None` if either
    #: run failed or the chunked run took 0ms (nothing to divide by).
    speedup: float | None = None
    error: str | None = None

    def to_dict(self) -> dict:
        """Convert to a dictionary for JSON serialization."""
        return {
            "size": self.size,
            "sources": self.sources,
            "maxParallel": self.max_parallel,
            "unchunkedSuccess": self.unchunked_success,
            "unchunkedMs": self.unchunked_ms,
            "unchunkedRuleCount": self.unchunked_rule_count,
            "chunkedSuccess": self.chunked_success,
            "chunkedMs": self.chunked_ms,
            "chunkedRuleCount": self.chunked_rule_count,
            "speedup": self.speedup,
            "error": self.error,
        }


def find_benchmark_data_dir() -> Path | None:
    """
    Locate the repo's `benchmarks/data` directory by walking up from the current
    directory, mirroring configuration-file discovery.
    """
    directory = Path.cwd()
    while True:
        candidate = directory / "benchmarks" / "data"
        if candidate.is_dir():
            return candidate
        if directory.parent == directory:
            return None
        directory = directory.parent


def build_benchmark_config(size: str, data_path: Path, num_sources: int) -> CompilerConfiguration:
    """
    Build a `CompilerConfiguration` with `num_sources` identical sources, all pointing at
    `data_path` - the same "N copies of one file" shape the (otherwise unusable,
    machine-specific-path) canned `benchmarks/data/config-multi-Nsources.json` fixtures
    use. Identical sources keep the unchunked and chunked runs directly comparable: same
    total workload, same total rule count after dedup, only the chunking strategy differs.
    """
    sources = [
        FilterSource(name=f"source-{i + 1}", source=str(data_path), type="adblock")
        for i in range(max(1, num_sources))
    ]

    return CompilerConfiguration(
        name=f"Benchmark - {size}",
        description=f"Real-pipeline benchmark of the '{size}' canned dataset",
        version="1.0.0",
        sources=sources,
        transformations=list(BENCHMARK_TRANSFORMATIONS),
    )


def _run_unchunked(config: CompilerConfiguration) -> tuple[bool, int, int, str | None]:
    """
    Run the unchunked path: write `config` to a temp JSON file and compile it through the
    real `BloqrCompiler.compile()` pipeline (a single compiler invocation covering all of
    `config`'s sources).
    """
    temp_dir = Path(tempfile.gettempdir())
    temp_config_path = temp_dir / f"benchmark-config-{uuid.uuid4()}.json"
    temp_output_path = temp_dir / f"benchmark-output-{uuid.uuid4()}.txt"

    try:
        temp_config_path.write_text(to_json(config), encoding="utf-8")

        result = BloqrCompiler().compile(
            config_path=temp_config_path,
            output_path=temp_output_path,
            validate=False,
        )
        return (
            result.success,
            result.elapsed_ms,
            result.rule_count,
            None if result.success else result.error_message,
        )
    finally:
        for path in (temp_config_path, temp_output_path):
            with contextlib.suppress(OSError):
                path.unlink(missing_ok=True)


def _run_chunked(config: CompilerConfiguration, max_parallel: int) -> tuple[bool, int, int, str | None]:
    """
    Run the chunked path: split `config` into one chunk per source (the only implemented
    chunking strategy) and compile the chunks in parallel through the real
    `compile_chunks_async()` pipeline, up to `max_parallel` at a time.
    """
    options = ChunkingOptions(
        enabled=True,
        max_parallel=max(1, max_parallel),
        strategy=ChunkingStrategy.SOURCE,
    )

    try:
        chunks = split_into_chunks(config, options)
        result = asyncio.run(compile_chunks_async(chunks, options))
        error = None if result.success else "; ".join(result.errors)
        return result.success, result.total_elapsed_ms, result.final_rule_count, error
    except Exception as e:
        # A benchmark run must report failure as data, not crash the whole `--benchmark` invocation.
        return False, 0, 0, str(e)


def run_benchmark(
    size: str = "all",
    data_dir: Path | None = None,
    num_sources: int = 4,
    max_parallel: int | None = None,
) -> list[BenchmarkRunResult]:
    """
    Benchmark real compilation performance (chunked vs unchunked) across the requested
    canned dataset size(s), using the same `BloqrCompiler.compile()`/`compile_chunks_async()`
    pipeline the standard compile mode uses - not a synthetic simulation.

    Args:
        size: Dataset size to benchmark (`small`/`medium`/`large`/`xlarge`), or `all`.
        data_dir: Directory containing the canned benchmark data. Auto-discovered if omitted.
        num_sources: Number of identical duplicated sources for the chunked run.
        max_parallel: Max parallel workers for the chunked run (default: CPU count, max 8).

    Returns:
        One `BenchmarkRunResult` per requested size.

    Raises:
        ValueError: If `size` is not a recognized dataset size or `all`.
        FileNotFoundError: If no `benchmarks/data` directory can be found or was given.
    """
    sizes = list(BENCHMARK_SIZES) if size.lower() == "all" else [size]

    invalid = next((s for s in sizes if s not in BENCHMARK_SIZES), None)
    if invalid is not None:
        raise ValueError(
            f"Unknown benchmark size '{invalid}'. Expected one of: {', '.join(BENCHMARK_SIZES)}, or 'all'."
        )

    resolved_data_dir = data_dir or find_benchmark_data_dir()
    if resolved_data_dir is None:
        raise FileNotFoundError(
            "Could not find a benchmarks/data directory. Pass data_dir to point at one "
            "explicitly, or run this from within a clone of BloqrAI/bloqr-core."
        )

    resolved_max_parallel = max_parallel if max_parallel is not None else min(os.cpu_count() or 4, 8)
    resolved_num_sources = max(1, num_sources)

    results: list[BenchmarkRunResult] = []

    for s in sizes:
        data_path = resolved_data_dir / f"{s}.txt"
        if not data_path.is_file():
            results.append(
                BenchmarkRunResult(
                    size=s,
                    sources=resolved_num_sources,
                    max_parallel=resolved_max_parallel,
                    error=f"dataset file not found: {data_path}",
                )
            )
            continue

        config = build_benchmark_config(s, data_path, resolved_num_sources)

        unchunked_success, unchunked_ms, unchunked_rule_count, unchunked_error = _run_unchunked(config)
        chunked_success, chunked_ms, chunked_rule_count, chunked_error = _run_chunked(
            config, resolved_max_parallel
        )

        speedup = (
            unchunked_ms / chunked_ms
            if unchunked_success and chunked_success and chunked_ms > 0
            else None
        )

        results.append(
            BenchmarkRunResult(
                size=s,
                sources=resolved_num_sources,
                max_parallel=resolved_max_parallel,
                unchunked_success=unchunked_success,
                unchunked_ms=unchunked_ms,
                unchunked_rule_count=unchunked_rule_count,
                chunked_success=chunked_success,
                chunked_ms=chunked_ms,
                chunked_rule_count=chunked_rule_count,
                speedup=speedup,
                error=unchunked_error or chunked_error,
            )
        )

    return results
